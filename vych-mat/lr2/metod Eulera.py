#1 порядок. Метод Эйлера

def f(x, y):
    return y*(1-x)
a = 0 #левая граница диапазона
b = 1 #правая граница диапазона
n = 10 #количество разбиений
x0 = 0
y0 = 1
h = (b-a)/n #шаг разбиений
print(f'Шаг интегрирования h = {h}')
print(f'x0 = {x0}')
print(f'y0 = {y0}')
y = y0
x = x0
while x < (b-h):
    y = y + h*f(x, y)
    print('x = ', round((x+h), 5), ' y = ', round(y, 5))
    x = x+h